def label_to_color(m) -> str:
    """Map an integer module label to a WGCNA colour name (0 -> grey)."""
    m = int(m)
    if m == 0:
        return "grey"
    idx = m - 1
    return WGCNA_COLORS[idx] if 0 <= idx < len(WGCNA_COLORS) else f"module{m}"


def module_size_table(labels: pd.Series, n_genes: int, log) -> pd.DataFrame:
    """[REV-4] sizes MUST sum to n_genes; enforced by assertion."""
    sizes = labels.value_counts().sort_index()
    tab = sizes.rename("n_genes").reset_index()
    tab.columns = ["module_label", "n_genes"]
    tab["color"] = tab["module_label"].apply(label_to_color)
    tab["module"] = tab["module_label"].apply(
        lambda m: "grey(unassigned)" if m == 0 else f"M{m}")
    tab = tab[["module", "color", "n_genes"]]
    total = int(sizes.sum())
    assert total == n_genes, (
        f"[REV-4] Module sizes sum to {total} but {n_genes} genes were analysed. "
        "This is exactly the inconsistency reviewers flagged.")
    log.info("Module sizes (sum == n_genes, verified):\n" + tab.to_string(index=False))
    return tab


