def download_geo(gse_id: str, cfg: Config, log):
    """Download a GEO series with GEOparse and return the GSE object."""
    import GEOparse
    os.makedirs(cfg.geo_dir, exist_ok=True)
    log.info(f"Loading {gse_id} from GEO (cache: {cfg.geo_dir}) ...")
    gse = GEOparse.get_GEO(geo=gse_id, destdir=cfg.geo_dir, silent=True,
                           annotate_gpl=True)
    return gse


def build_expression_matrix(gse, log) -> pd.DataFrame:
    """
    Return a probe x sample expression DataFrame.
    Works for typical single-platform microarray series.
    """
    expr = gse.pivot_samples("VALUE")          # rows = probes, cols = GSM ids
    expr = expr.apply(pd.to_numeric, errors="coerce")
    expr = expr.dropna(how="all")
    log.info(f"Raw expression matrix: {expr.shape[0]} probes x {expr.shape[1]} samples")
    return expr


def map_probes_to_genes(gse, expr: pd.DataFrame, log) -> pd.DataFrame:
    """
    Collapse probes to gene symbols using the platform annotation.
    Strategy = MaxMean: for each gene keep the probe with the highest mean signal
    (mirrors WGCNA::collapseRows 'MaxMean'). [REV-9 reproducibility]
    """
    gpl = list(gse.gpls.values())[0]
    ann = gpl.table.copy()
    # find a gene-symbol column heuristically
    candidates = ["Gene Symbol", "Gene symbol", "GENE_SYMBOL", "Symbol",
                  "gene_symbol", "ILMN_Gene", "GeneSymbol", "Gene_Symbol"]
    sym_col = next((c for c in candidates if c in ann.columns), None)
    id_col = "ID" if "ID" in ann.columns else ann.columns[0]
    if sym_col is None:
        log.warning("No gene-symbol column found in platform annotation; "
                    "keeping probe IDs. Inspect gpl.table.columns and set sym_col.")
        return expr
    ann = ann[[id_col, sym_col]].dropna()
    ann[sym_col] = (ann[sym_col].astype(str)
                    .str.split("///").str[0].str.strip())     # first symbol
    ann = ann[ann[sym_col].str.len() > 0]
    probe2gene = dict(zip(ann[id_col].astype(str), ann[sym_col]))

    expr = expr.copy()
    expr.index = expr.index.astype(str)
    expr["__gene__"] = expr.index.map(probe2gene)
    expr = expr.dropna(subset=["__gene__"])
    expr["__mean__"] = expr.drop(columns="__gene__").mean(axis=1)
    # MaxMean collapse
    expr = (expr.sort_values("__mean__", ascending=False)
                .drop_duplicates("__gene__", keep="first"))
    expr = expr.set_index("__gene__").drop(columns="__mean__")
    expr.index.name = "gene"
    log.info(f"After probe->gene MaxMean collapse: {expr.shape[0]} genes")
    return expr


def parse_metadata(gse, log) -> pd.DataFrame:
    """
    Parse per-sample phenotype from GEO 'characteristics_ch1'.
    Produces columns: AD (0/1), sex, age, region, batch (best effort).
    EDIT the keyword lists below to match the exact wording in your series.
    [REV-1 single dataset, REV-9 covariates declared]
    """
    rows = {}
    for gsm_id, gsm in gse.gsms.items():
        meta = " ; ".join(gsm.metadata.get("characteristics_ch1", [])).lower()
        title = " ".join(gsm.metadata.get("title", [])).lower()
        blob = meta + " ; " + title

        # diagnosis
        ad = np.nan
        if any(k in blob for k in ["alzheimer", "ad ", ": ad", "case", "disease: ad"]):
            ad = 1
        if any(k in blob for k in ["control", "normal", "non-demented", "nd ",
                                   "cognitively normal", "ctrl"]):
            ad = 0 if np.isnan(ad) else ad
        # sex
        sex = np.nan
        if any(k in blob for k in [" female", "sex: f", "gender: f", "f-ad", "f-control"]):
            sex = 0
        if any(k in blob for k in [" male", "sex: m", "gender: m", "m-ad", "m-control"]):
            sex = 1
        # age
        age = np.nan
        import re
        m = re.search(r"age[^0-9]{0,8}(\d{2,3})", blob)
        if m:
            age = float(m.group(1))
        # region (GSE29378 = CA1 / CA3)
        region = np.nan
        if "ca1" in blob: region = "CA1"
        elif "ca3" in blob: region = "CA3"
        # braak / cerad if present (continuous traits) [REV-9]
        braak = np.nan
        mb = re.search(r"braak[^0-9]{0,8}(\d)", blob)
        if mb: braak = float(mb.group(1))

        rows[gsm_id] = dict(AD=ad, sex=sex, age=age, region=region, braak=braak)

    meta = pd.DataFrame(rows).T
    log.info("Parsed metadata (head):\n" + meta.head().to_string())
    n_ad = int((meta["AD"] == 1).sum()); n_ct = int((meta["AD"] == 0).sum())
    log.info(f"Diagnosis counts -> AD: {n_ad}, Control: {n_ct}, "
             f"Unknown: {int(meta['AD'].isna().sum())}")
    if n_ad == 0 or n_ct == 0:
        log.warning("Could not resolve AD/control from metadata automatically. "
                    "Inspect gse.gsms[...].metadata['characteristics_ch1'] and "
                    "edit parse_metadata().")
    return meta


