def run(cfg: Config, skip_download: bool):
    np.random.seed(cfg.seed)
    out_dir = cfg.out_dir
    log = setup_logging(out_dir)
    log.info("=" * 70)
    log.info("AD WGCNA reproducible pipeline")
    log.info(f"Primary dataset (REV-1): {cfg.primary_gse} | "
             f"network_type={cfg.network_type} | seed={cfg.seed}")
    log.info("=" * 70)

    # --- 1. Discovery data --------------------------------------------------
    gse = download_geo(cfg.primary_gse, cfg, log)
    expr = build_expression_matrix(gse, log)
    expr = map_probes_to_genes(gse, expr, log)
    meta = parse_metadata(gse, log)

    # keep only samples with known diagnosis
    meta = meta[meta["AD"].notna()]
    expr = expr[meta.index]
    expr = maybe_log2(expr, log)
    expr = filter_genes(expr, cfg, log)

    datExpr = expr.T                                # samples x genes
    datExpr = detect_sample_outliers(datExpr, cfg, log)
    meta = meta.loc[datExpr.index]
    datExpr = adjust_covariates(datExpr, meta, cfg, log)
    datExpr = drop_invariant_genes(datExpr, cfg, log)
    n_genes = datExpr.shape[1]
    log.info(f"FINAL discovery matrix: {datExpr.shape[0]} samples x {n_genes} genes")

    # --- 3. Soft threshold --------------------------------------------------
    beta, sft_tab, corr = pick_soft_threshold(datExpr, cfg, log)
    sft_tab.to_csv(os.path.join(out_dir, "soft_threshold_table.csv"), index=False)

    # --- 4. Network ---------------------------------------------------------
    adj = adjacency(corr, beta, cfg.network_type)
    TOM = topological_overlap(adj)
    dissTOM = 1 - TOM

    # --- 5. Modules ---------------------------------------------------------
    raw_labels, _ = detect_modules(dissTOM, datExpr.columns, cfg, log)
    labels, MEs = merge_close_modules(datExpr, raw_labels, cfg, log)
    size_tab = module_size_table(labels, n_genes, log)        # asserts sum==n_genes
    size_tab.to_csv(os.path.join(out_dir, "module_sizes.csv"), index=False)

    # --- inputs for the R preservation companion (ad_wgcna_validation.R) -----
    # discovery_expr.csv : genes (rows) x samples (cols)
    datExpr.T.to_csv(os.path.join(out_dir, "discovery_expr.csv"))
    # module_colors.csv : gene,module  (module = WGCNA colour; grey = unassigned)
    mc = labels.map(label_to_color).reset_index()
    mc.columns = ["gene", "module"]
    mc.to_csv(os.path.join(out_dir, "module_colors.csv"), index=False)
    log.info("Wrote R-companion inputs: discovery_expr.csv, module_colors.csv "
             "(validation_expr.csv is written during the preservation step).")

    # --- 6. Module-trait ----------------------------------------------------
    mt_res, sig = module_trait(MEs, meta, cfg, log)
    mt_res.to_csv(os.path.join(out_dir, "module_trait.csv"), index=False)
    sig_modules = sig["module"].tolist()

    # --- 7. GS / MM / hubs --------------------------------------------------
    gsmm = gs_mm_hub(datExpr, labels, MEs, meta, cfg, log)
    gsmm.to_csv(os.path.join(out_dir, "gene_significance_module_membership.csv"))

    # --- 8. Risk-gene enrichment -------------------------------------------
    risk = risk_gene_enrichment(labels, log)
    risk.to_csv(os.path.join(out_dir, "risk_gene_enrichment.csv"), index=False)

    # --- 9. Functional enrichment ------------------------------------------
    enr_summary = functional_enrichment(labels, sig_modules, cfg, out_dir, log)

    # --- 10. Preservation ---------------------------------------------------
    preservation = None
    try:
        gse_val = download_geo(cfg.validation_gse, cfg, log)
        val_expr = build_expression_matrix(gse_val, log)
        val_expr = map_probes_to_genes(gse_val, val_expr, log)
        val_expr = maybe_log2(val_expr, log).T          # samples x genes
        # validation_expr.csv for the R companion: genes (rows) x samples (cols),
        # restricted to the discovery gene set the modules are defined on.
        common_val = [g for g in datExpr.columns if g in val_expr.columns]
        val_expr[common_val].T.to_csv(
            os.path.join(out_dir, "validation_expr.csv"))
        log.info(f"Wrote validation_expr.csv ({len(common_val)} genes shared "
                 f"with discovery) for the R companion.")
        preservation = module_preservation(datExpr, labels, val_expr, cfg, log)
        preservation.to_csv(os.path.join(out_dir, "module_preservation.csv"), index=False)
    except Exception as e:
        log.warning(f"Preservation step skipped ({e}). "
                    "Run with internet access to GEO, or use the R companion.")

    # --- 11. Figures --------------------------------------------------------
    make_figures(sft_tab, mt_res, MEs, meta, labels, gsmm, out_dir, log)

    # --- run manifest (reproducibility) ------------------------------------
    manifest = dict(
        timestamp=datetime.now().isoformat(timespec="seconds"),
        primary_dataset=cfg.primary_gse, validation_dataset=cfg.validation_gse,
        n_samples=int(datExpr.shape[0]), n_genes=int(n_genes),
        network_type=cfg.network_type, beta=beta,
        n_modules=int(labels[labels != 0].nunique()),
        ad_associated_modules=sig_modules,
        enrichment_summary=enr_summary,
        config={k: (list(v) if isinstance(v, tuple) else v)
                for k, v in cfg.__dict__.items()},
        package_versions={p: __import__(p).__version__ for p in
                          ["numpy", "pandas", "scipy", "sklearn",
                           "statsmodels", "gseapy"]},
    )
    with open(os.path.join(out_dir, "run_manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=2, default=str)
    log.info(f"Done. All outputs in ./{out_dir}/")
    log.info("Use module_sizes.csv, module_trait.csv, risk_gene_enrichment.csv, "
             "enrichment_*.csv and module_preservation.csv as the manuscript's "
             "quantitative tables (replace the descriptive bullet lists).")


