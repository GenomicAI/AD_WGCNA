# 8. AD RISK-GENE ENRICHMENT (Fisher exact, explicit background)         [REV-9]
# ==============================================================================
def risk_gene_enrichment(labels: pd.Series, log) -> pd.DataFrame:
    """
    Background = all genes that entered the network (NOT the whole genome).
    [REV-9: background explicitly the analysis universe]
    """
    universe = set(labels.index)
    risk_in_universe = universe & set(AD_RISK_GENES)
    log.info(f"AD risk genes present in analysis universe: "
             f"{len(risk_in_universe)}/{len(AD_RISK_GENES)}")
    rows = []
    for m in sorted(labels.unique()):
        if m == 0:
            continue
        mod_genes = set(labels.index[labels == m])
        a = len(mod_genes & risk_in_universe)          # risk & in module
        b = len(mod_genes) - a                          # non-risk & in module
        c = len(risk_in_universe) - a                   # risk & not in module
        d = len(universe) - a - b - c
        OR, p = fisher_exact([[a, b], [c, d]], alternative="greater")
        rows.append(dict(module=f"ME{m}", n_module=len(mod_genes),
                         n_risk_in_module=a, odds_ratio=OR, p=p,
                         risk_genes=";".join(sorted(mod_genes & risk_in_universe))))
    res = pd.DataFrame(rows)
    if len(res):
        res["p_adj_BH"] = multipletests(res["p"], method="fdr_bh")[1]
        res = res.sort_values("p")
    log.info("AD risk-gene enrichment per module:\n" +
             res[["module", "n_module", "n_risk_in_module",
                  "odds_ratio", "p", "p_adj_BH"]].to_string(index=False))
    return res


