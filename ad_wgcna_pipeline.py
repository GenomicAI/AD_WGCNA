# 9. FUNCTIONAL ENRICHMENT (GO / KEGG)                                   [REV-8,9]
# ==============================================================================
def functional_enrichment(labels, sig_modules, cfg, out_dir, log):
    """
    Run Enrichr for EVERY non-grey module with an explicit background, writing
    enrichment_ME*.csv per module. Module biology is read FROM this output, not
    asserted [REV-8]. We enrich all modules (not only trait-significant ones)
    because the most interpretable module biologically may be a risk-gene or
    preservation hit rather than a case/control hit (e.g. a microglial module
    that is strongly GWAS-enriched but only weakly trait-correlated).
    """
    if not cfg.run_enrichr:
        log.info("run_enrichr=False -> skipping GO/KEGG (offline mode).")
        return {}
    import gseapy as gp
    background = list(labels.index)
    sig_set = set(sig_modules)
    all_modules = [f"ME{m}" for m in sorted(labels.unique()) if m != 0]
    summaries = {}
    for me in all_modules:
        m = int(me[2:])
        genes = list(labels.index[labels == m])
        if len(genes) < 5:
            continue
        try:
            enr = gp.enrichr(gene_list=genes, gene_sets=list(cfg.enrichr_gene_sets),
                             background=background, outdir=None)
            res = enr.results
            res = res[res["Adjusted P-value"] < cfg.enrichment_fdr_cut]
            res = res.sort_values("Adjusted P-value")
            res.to_csv(os.path.join(out_dir, f"enrichment_{me}.csv"), index=False)
            top_terms = res["Term"].head(5).tolist()
            summaries[me] = top_terms
            tag = " [trait-significant]" if me in sig_set else ""
            log.info(f"{me}{tag}: {len(res)} terms at FDR<{cfg.enrichment_fdr_cut}; "
                     f"top: {top_terms}")
        except Exception as e:                          # network / API issues
            log.warning(f"Enrichr failed for {me}: {e}. "
                        "Re-run with internet access or use a local GMT.")
    return summaries


