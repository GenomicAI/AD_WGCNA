# 3. SOFT-THRESHOLD POWER SELECTION                                      [REV-3]
# ==============================================================================
def adjacency(corr: np.ndarray, power: float, network_type: str) -> np.ndarray:
    if network_type == "signed":
        a = ((1 + corr) / 2.0) ** power
    elif network_type == "signed hybrid":
        a = np.where(corr > 0, corr, 0.0) ** power
    else:  # unsigned
        a = np.abs(corr) ** power
    np.fill_diagonal(a, 0.0)
    return a


def scale_free_fit_index(k: np.ndarray, n_breaks: int = 10):
    """
    Signed scale-free topology fit R^2, mirroring WGCNA::scaleFreeFitIndex.

    Critically, this uses EQUAL-WIDTH bins of connectivity k (R's cut()), NOT
    equal-frequency quantile bins. The log-log regression is log10(p(k)) on
    log10(k); equal-frequency bins force every bin to hold the same number of
    genes, so p(k) is constant, ss_tot == 0, and R^2 is undefined for every
    power. Equal-width bins recover the actual degree distribution, where p(k)
    falls off as k grows (the hallmark of scale-free topology).

    Returns (signed R^2, slope). A good fit has slope < 0, reported as +R^2.
    """
    k = k[np.isfinite(k) & (k >= 0)]
    if len(k) < n_breaks + 1:
        return np.nan, np.nan
    kmin, kmax = float(k.min()), float(k.max())
    if kmax <= kmin:                       # no spread -> undefined
        return np.nan, np.nan
    edges = np.linspace(kmin, kmax, n_breaks + 1)
    mids = 0.5 * (edges[:-1] + edges[1:])
    # right-closed bins, like R's cut(..., right = TRUE)
    binidx = np.clip(np.digitize(k, edges[1:-1], right=True), 0, n_breaks - 1)
    counts = np.bincount(binidx, minlength=n_breaks).astype(float)
    sum_k = np.bincount(binidx, weights=k, minlength=n_breaks)
    # mean k per bin; empty bins fall back to the bin midpoint (WGCNA does this)
    mean_k = np.where(counts > 0, sum_k / np.maximum(counts, 1.0), mids)
    mean_k = np.where(mean_k > 0, mean_k, mids)
    p_k = counts / len(k)
    x = np.log10(mean_k)
    y = np.log10(p_k + 1e-9)               # pseudo-count for empty bins (WGCNA)
    if np.std(x) == 0 or len(x) < 3:
        return np.nan, np.nan
    slope, intercept = np.polyfit(x, y, 1)
    yhat = slope * x + intercept
    ss_res = float(np.sum((y - yhat) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else np.nan
    return float(-np.sign(slope) * r2), float(slope)  # slope<0 => positive R^2



def pick_soft_threshold(datExpr: pd.DataFrame, cfg: Config, log) -> tuple:
    """
    Mirror WGCNA::pickSoftThreshold. Returns (chosen_power, table DataFrame).
    [REV-3: data-driven beta + diagnostic table/plot, never hard-coded 1]
    """
    corr = np.corrcoef(datExpr.values.T)            # genes x genes
    # Belt-and-suspenders: a residual NaN/inf here (e.g. a constant gene that
    # slipped through) would otherwise poison every connectivity sum and make
    # the whole scale-free table NaN. drop_invariant_genes() should prevent it.
    n_bad = int((~np.isfinite(corr)).sum())
    if n_bad:
        log.warning(f"{n_bad} non-finite entr(ies) in correlation matrix set "
                    f"to 0; check for invariant genes upstream.")
        corr = np.nan_to_num(corr, nan=0.0, posinf=0.0, neginf=0.0)
    np.fill_diagonal(corr, 0.0)
    recs = []
    for p in cfg.powers:
        a = adjacency(corr, p, cfg.network_type)
        k = a.sum(axis=1)
        sft, slope = scale_free_fit_index(k)
        recs.append(dict(power=p, SFT_R2=sft, slope=slope,
                         mean_k=float(k.mean()), median_k=float(np.median(k)),
                         max_k=float(k.max())))
    tab = pd.DataFrame(recs)
    if tab["SFT_R2"].isna().all():
        raise ValueError(
            "Scale-free fit (SFT_R2) is NaN for every candidate power. This "
            "almost always means the gene-gene correlation matrix is "
            "degenerate (constant/duplicated genes or too few samples). "
            "Verify drop_invariant_genes() ran and that datExpr is "
            "samples x genes with adequate variance.")
    eligible = tab[tab["SFT_R2"] >= cfg.sft_r2_cut]
    if getattr(cfg, "manual_power", None):
        chosen = int(cfg.manual_power)
        log.info(f"Using user-specified soft-threshold power beta = {chosen} "
                 f"(--power override; SFT table still written for the record).")
    elif len(eligible):
        chosen = int(eligible["power"].iloc[0])      # lowest power past the cut
    else:
        # R^2 rises monotonically with beta, so idxmax would just return the
        # largest power tested and over-sparsify the network. WGCNA's FAQ
        # instead recommends a sample-size-based default when the R^2 target
        # is never reached. Use that, floored so the network stays connected.
        n_samples = datExpr.shape[0]
        chosen = wgcna_default_power(n_samples, cfg.network_type)
        best_p = int(tab.loc[tab["SFT_R2"].idxmax(), "power"])
        best_r2 = float(tab["SFT_R2"].max())
        log.warning(
            f"No power reached R^2>={cfg.sft_r2_cut} (best R^2={best_r2:.2f} at "
            f"power={best_p}). Falling back to WGCNA sample-size default "
            f"beta={chosen} for n={n_samples} {cfg.network_type} samples. "
            f"Inspect soft_threshold_table.csv; override with --power if needed.")
    log.info(f"Chosen soft-threshold power beta = {chosen} "
             f"(network_type={cfg.network_type})")
    if chosen == 1:
        log.warning("beta==1 selected -- inspect the SFT table; this usually "
                    "indicates a problem and was a key reviewer concern.")
    return chosen, tab, corr


def wgcna_default_power(n_samples: int, network_type: str) -> int:
    """
    WGCNA's recommended soft-threshold power when the scale-free R^2 target is
    not reached, as a function of sample size and network type
    (Langfelder & Horvath WGCNA FAQ). Signed/signed-hybrid networks use roughly
    double the unsigned power.
    """
    signed = network_type in ("signed", "signed hybrid")
    if n_samples < 20:
        return 18 if signed else 9
    if n_samples < 30:
        return 16 if signed else 8
    if n_samples < 40:
        return 14 if signed else 7
    return 12 if signed else 6


# ==============================================================================
# 4. NETWORK CONSTRUCTION (TOM)                                          [REV-3]
# ==============================================================================
def topological_overlap(a: np.ndarray) -> np.ndarray:
    """Unsigned TOM (works on non-negative signed adjacency too)."""
    L = a @ a                                   # shared-neighbour connectivity
    k = a.sum(axis=1)
    k_min = np.minimum.outer(k, k)
    denom = k_min + 1 - a
    tom = (L + a) / denom
    np.fill_diagonal(tom, 1.0)
    tom = np.clip(tom, 0, 1)
    return tom


