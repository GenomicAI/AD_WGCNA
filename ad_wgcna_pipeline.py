# 10. MODULE PRESERVATION (independent dataset)                          [REV-7]
# ==============================================================================
def module_preservation(disc_expr, disc_labels, val_expr, cfg, log):
    """
    Permutation-based approximation of WGCNA::modulePreservation Z-summary.
    For each discovery module we test, in the VALIDATION cohort, two stable
    statistics (Langfelder et al. 2011, simplified):
      density      : meanCor  = mean pairwise |correlation| among the module's
                     genes in the validation data (high if the module stays
                     densely co-expressed).
      connectivity : cor.kME  = correlation between each gene's connectivity to
                     the module eigengene in DISCOVERY vs VALIDATION (high if the
                     internal connectivity ranking is reproduced).
    Z = (observed - mean_permuted) / sd_permuted, with random equal-sized gene
    sets as the null; Z is clipped to +/-50 for numerical stability.
    Zsummary = mean(Zdensity, Zconnectivity).
    Thresholds: Zsummary > 10 strong, 2-10 moderate, < 2 not preserved.
    NOTE: for a publication-grade statistic, ALSO run WGCNA::modulePreservation
    in R (see the ad_wgcna_validation.R companion). [REV-7]
    """
    rng = np.random.default_rng(cfg.seed)
    common = sorted(set(disc_expr.columns) & set(val_expr.columns))
    log.info(f"Preservation: {len(common)} genes common to discovery & validation.")
    if len(common) > cfg.preservation_max_genes:
        v = val_expr[common].var().sort_values(ascending=False)
        common = list(v.index[:cfg.preservation_max_genes])
    disc_e = disc_expr[common]; val_e = val_expr[common]
    lab = disc_labels.loc[common]

    val_corr = np.corrcoef(val_e.values.T); np.fill_diagonal(val_corr, 0)
    disc_corr = np.corrcoef(disc_e.values.T); np.fill_diagonal(disc_corr, 0)
    gene_idx = {g: i for i, g in enumerate(common)}

    def density_stat(idx):
        sub = np.abs(val_corr[np.ix_(idx, idx)])
        return sub[np.triu_indices(len(idx), 1)].mean()

    def conn_stat(idx):
        # cor.cor: agreement between the pairwise-correlation PATTERNS of the
        # module in discovery vs validation (robust; no kME-variance dependence).
        iu = np.triu_indices(len(idx), 1)
        cd = disc_corr[np.ix_(idx, idx)][iu]
        cv = val_corr[np.ix_(idx, idx)][iu]
        if cd.std() < 1e-6 or cv.std() < 1e-6:
            return 0.0
        return abs(np.corrcoef(cd, cv)[0, 1])

    def _z(obs, perm):
        perm = np.asarray(perm)
        sd = perm.std()
        if sd < 1e-6:
            return 0.0
        return float(np.clip((obs - perm.mean()) / sd, -50, 50))

    results = []
    for m in sorted(lab.unique()):
        if m == 0:
            continue
        mgenes = [g for g in common if lab[g] == m]
        if len(mgenes) < cfg.min_module_size:
            continue
        ii = np.array([gene_idx[g] for g in mgenes])
        obs_d = density_stat(ii); obs_c = conn_stat(ii)
        perm_d, perm_c = [], []
        for _ in range(cfg.preservation_perms):
            ridx = rng.choice(len(common), size=len(ii), replace=False)
            perm_d.append(density_stat(ridx)); perm_c.append(conn_stat(ridx))
        Zd = _z(obs_d, perm_d); Zc = _z(obs_c, perm_c)
        Zsum = np.mean([Zd, Zc])
        verdict = ("strong" if Zsum > 10 else
                   "moderate" if Zsum > 2 else "not preserved")
        results.append(dict(module=f"ME{m}", n_genes=len(mgenes),
                            meanCor=round(obs_d, 3), corCor=round(obs_c, 3),
                            Zdensity=round(Zd, 2), Zconnectivity=round(Zc, 2),
                            Zsummary=round(Zsum, 2), preservation=verdict))
    res = pd.DataFrame(results).sort_values("Zsummary", ascending=False)
    res["medianRank"] = res["Zsummary"].rank(ascending=False).astype(int)
    log.info("Module preservation (Zsummary):\n" + res.to_string(index=False))
    return res


