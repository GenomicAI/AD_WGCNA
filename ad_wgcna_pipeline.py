# 6. MODULE-TRAIT RELATIONSHIPS                                          [REV-8,9]
# ==============================================================================
def correlate_pvalue(x, y):
    x = np.asarray(x, float); y = np.asarray(y, float)
    ok = ~(np.isnan(x) | np.isnan(y))
    x, y = x[ok], y[ok]
    n = len(x)
    if n < 4 or x.std() == 0 or y.std() == 0:
        return np.nan, np.nan
    r = np.corrcoef(x, y)[0, 1]
    tval = r * np.sqrt((n - 2) / max(1e-12, 1 - r ** 2))
    p = 2 * t_dist.sf(abs(tval), df=n - 2)
    return float(r), float(p)


def module_trait(MEs: pd.DataFrame, meta: pd.DataFrame, cfg: Config, log):
    """
    Correlate every module eigengene with binary AD status AND continuous
    pathology traits (braak) plus covariates for transparency. Report exact
    BH-adjusted p-values. [REV-8 reconcile biology, REV-9 exact padj & traits]
    """
    traits = {}
    md = meta.loc[MEs.index]
    traits["AD_status"] = md["AD"].astype(float)
    for t in ("braak", "age", "sex"):
        if t in md.columns and md[t].notna().sum() > 4:
            traits[t] = md[t].astype(float)
    rows = []
    for me in MEs.columns:
        for tname, tvals in traits.items():
            r, p = correlate_pvalue(MEs[me].values, tvals.values)
            rows.append(dict(module=me, trait=tname, r=r, p=p))
    res = pd.DataFrame(rows)
    res["p_adj_BH"] = np.nan
    ok = res["p"].notna()
    res.loc[ok, "p_adj_BH"] = multipletests(res.loc[ok, "p"], method="fdr_bh")[1]
    sig = res[(res["trait"] == "AD_status")
              & (res["r"].abs() >= cfg.mt_abs_r_cut)
              & (res["p_adj_BH"] < cfg.mt_padj_cut)].copy()
    log.info(f"Modules significantly associated with AD status "
             f"(|r|>={cfg.mt_abs_r_cut}, padj<{cfg.mt_padj_cut}): "
             f"{sig['module'].tolist()}")
    return res, sig


