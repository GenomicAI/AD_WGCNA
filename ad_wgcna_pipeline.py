def maybe_log2(expr: pd.DataFrame, log) -> pd.DataFrame:
    if np.nanmax(expr.values) > 50:           # looks like linear-scale intensities
        log.info("Applying log2(x+1) (data appeared to be on a linear scale).")
        expr = np.log2(expr.clip(lower=0) + 1)
    return expr


def filter_genes(expr: pd.DataFrame, cfg: Config, log) -> pd.DataFrame:
    expr = expr.loc[expr.mean(axis=1) >= cfg.min_mean_expr]
    cv = expr.std(axis=1)
    keep = cv >= cv.quantile(1 - cfg.var_quantile_keep)
    expr = expr.loc[keep]
    log.info(f"After expression+variance filtering: {expr.shape[0]} genes")
    # cap at most-variable N for network construction (standard WGCNA practice)
    if expr.shape[0] > cfg.n_top_genes_network:
        top = expr.var(axis=1).sort_values(ascending=False).index[:cfg.n_top_genes_network]
        expr = expr.loc[top]
        log.info(f"Restricted to top {cfg.n_top_genes_network} most-variable genes.")
    return expr


def detect_sample_outliers(datExpr: pd.DataFrame, cfg: Config, log) -> pd.DataFrame:
    """
    datExpr = samples x genes. Flag outliers by standardised total connectivity
    (mirrors WGCNA recommended sample network Z.k approach).
    """
    A = np.corrcoef(datExpr.values)
    np.fill_diagonal(A, 0)
    k = A.sum(axis=1)
    Z = (k - k.mean()) / k.std()
    outliers = datExpr.index[Z < -cfg.outlier_z_thresh]
    if len(outliers):
        log.info(f"Removing {len(outliers)} outlier sample(s): {list(outliers)}")
        datExpr = datExpr.drop(index=outliers)
    else:
        log.info("No sample outliers detected.")
    return datExpr


def adjust_covariates(datExpr: pd.DataFrame, meta: pd.DataFrame,
                      cfg: Config, log) -> pd.DataFrame:
    """
    Regress technical/biological covariates out of each gene (limma
    removeBatchEffect style) while PROTECTING the AD signal of interest.
    [REV-9: sex/age/region/batch modelled and removed; AD kept]
    """
    import statsmodels.api as sm
    covs = [c for c in cfg.covariates if c in meta.columns]
    md = meta.loc[datExpr.index]
    # build design: covariates to remove + AD to retain
    X_parts = []
    for c in covs:
        col = md[c]
        if col.dtype == object:                      # categorical e.g. region
            d = pd.get_dummies(col, prefix=c, drop_first=True).astype(float)
            X_parts.append(d)
        else:
            X_parts.append(col.astype(float).to_frame(c))
    if not X_parts:
        log.info("No covariates available to adjust; skipping covariate removal.")
        return datExpr
    Xcov = pd.concat(X_parts, axis=1)
    # impute simple means for missing covariate values
    Xcov = Xcov.fillna(Xcov.mean())
    keep_signal = md["AD"].astype(float).fillna(md["AD"].mean()).to_frame("AD")
    design = sm.add_constant(pd.concat([keep_signal, Xcov], axis=1).astype(float))

    adj = datExpr.copy()
    cov_cols = list(Xcov.columns)
    for g in datExpr.columns:
        y = datExpr[g].values
        model = sm.OLS(y, design.values).fit()
        beta = pd.Series(model.params, index=design.columns)
        # subtract only the covariate contributions, keep AD + intercept + resid
        adj[g] = y - design[cov_cols].values @ beta[cov_cols].values
    log.info(f"Regressed out covariates {cov_cols} (AD effect preserved).")
    return adj


def drop_invariant_genes(datExpr: pd.DataFrame, cfg: Config, log,
                         sd_floor: float = 1e-8) -> pd.DataFrame:
    """
    Remove genes that are non-finite or have (near-)zero variance.

    WGCNA's goodGenes() does the equivalent. This MUST run after covariate
    adjustment: regressing out sex/region/age can flatten a gene to a constant,
    and a single zero-variance column makes np.corrcoef emit a NaN row/column,
    which then propagates to every connectivity sum and makes the entire
    scale-free fit table NaN (the cause of "Encountered all NA values").
    """
    sd = datExpr.std(axis=0, ddof=1)
    finite = np.isfinite(datExpr.values).all(axis=0)
    keep = (sd.values > sd_floor) & finite
    n_drop = int((~keep).sum())
    if n_drop:
        dropped = list(datExpr.columns[~keep][:10])
        log.warning(
            f"Dropping {n_drop} invariant/non-finite gene(s) after covariate "
            f"adjustment (zero variance breaks the correlation matrix). "
            f"e.g. {dropped}")
    return datExpr.loc[:, keep]


