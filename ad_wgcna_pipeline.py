# 7. GENE SIGNIFICANCE, MODULE MEMBERSHIP, HUB GENES                     [REV-8]
# ==============================================================================
def gs_mm_hub(datExpr, labels, MEs, meta, cfg, log):
    ad = meta.loc[datExpr.index, "AD"].astype(float).values
    GS = {}
    for g in datExpr.columns:
        r, _ = correlate_pvalue(datExpr[g].values, ad)
        GS[g] = abs(r) if r == r else np.nan
    GS = pd.Series(GS, name="GS")

    MM = pd.Series(index=datExpr.columns, dtype=float, name="MM")
    for g in datExpr.columns:
        m = labels[g]
        if m == 0 or f"ME{m}" not in MEs.columns:
            continue
        r, _ = correlate_pvalue(datExpr[g].values, MEs[f"ME{m}"].values)
        MM[g] = r
    df = pd.concat([labels.rename("module"), GS, MM], axis=1)
    df["is_hub"] = (df["MM"].abs() >= cfg.hub_mm_cut) & (df["GS"] >= cfg.hub_gs_cut)
    df["is_AD_risk_gene"] = df.index.isin(AD_RISK_GENES)
    log.info(f"Hub genes (MM>={cfg.hub_mm_cut} & GS>={cfg.hub_gs_cut}): "
             f"{int(df['is_hub'].sum())}")
    return df


