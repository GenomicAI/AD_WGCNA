def detect_modules(dissTOM: np.ndarray, genes, cfg: Config, log) -> pd.Series:
    from dynamicTreeCut import cutreeHybrid
    Z = linkage(squareform(dissTOM, checks=False), method="average")
    # NOTE: the dynamicTreeCut PyPI port has a defect in its
    # pamRespectsDendro=False branch (references an undefined name). We therefore
    # use pamRespectsDendro=True (the WGCNA-default behaviour, and bug-free),
    # and fall back to pamStage=False if any PAM-stage error is raised.
    try:
        cut = cutreeHybrid(Z, distM=dissTOM, deepSplit=cfg.deep_split,
                           minClusterSize=cfg.min_module_size,
                           pamRespectsDendro=True, verbose=0)
    except Exception as e:
        log.warning(f"PAM stage failed ({e}); retrying with pamStage=False.")
        cut = cutreeHybrid(Z, distM=dissTOM, deepSplit=cfg.deep_split,
                           minClusterSize=cfg.min_module_size,
                           pamStage=False, verbose=0)
    labels = pd.Series(cut["labels"], index=genes, name="module")
    log.info(f"Dynamic tree cut -> {labels.nunique()} raw modules "
             f"(incl. label 0 = unassigned/grey).")
    return labels, Z


def module_eigengenes(datExpr: pd.DataFrame, labels: pd.Series) -> pd.DataFrame:
    """First PC per module, sign-aligned to mean expression."""
    MEs = {}
    for m in sorted(labels.unique()):
        if m == 0:
            continue
        genes = labels.index[labels == m]
        X = datExpr[genes].values
        X = (X - X.mean(0)) / (X.std(0) + 1e-9)
        u, s, vt = np.linalg.svd(X, full_matrices=False)
        pc1 = u[:, 0] * s[0]
        # sign alignment
        if np.corrcoef(pc1, X.mean(1))[0, 1] < 0:
            pc1 = -pc1
        MEs[f"ME{m}"] = pc1
    return pd.DataFrame(MEs, index=datExpr.index)


def merge_close_modules(datExpr, labels, cfg, log):
    """Merge modules whose eigengenes correlate > 1 - merge_cut_height. [REV-8]"""
    MEs = module_eigengenes(datExpr, labels)
    if MEs.shape[1] <= 1:
        return labels, MEs
    cor = np.corrcoef(MEs.values.T)
    diss = 1 - cor
    Z = linkage(squareform(np.clip(diss, 0, 2), checks=False), method="average")
    grp = fcluster(Z, t=cfg.merge_cut_height, criterion="distance")
    me_names = list(MEs.columns)
    old2new = {}
    for me_name, g in zip(me_names, grp):
        old = int(me_name[2:])
        old2new[old] = g
    new_labels = labels.copy()
    mask = new_labels != 0
    new_labels[mask] = new_labels[mask].map(old2new)
    log.info(f"Module merge (cutHeight={cfg.merge_cut_height}): "
             f"{labels[labels!=0].nunique()} -> {new_labels[new_labels!=0].nunique()} modules.")
    MEs = module_eigengenes(datExpr, new_labels)
    return new_labels, MEs


